// BDHC: mikelan98 and JayT, with Hiro TDK's incline descriptions:
// https://projectpokemon.org/home/forums/topic/37816-gen-iv-bdhc-files-terrain-settings/
// https://hirotdk.neocities.org/FileSpecs
// Gen 5 permissions and distance indices: Gonhex and Trifindo:
// https://ds-pokemon-hacking.github.io/docs/generation-v/resources/bw_b2w2-maps/
// These readers return the existing export's compact JSON, including its CRLF.
const f = Math.fround;
const decimal = n => Object.is(n, -0) ? '-0.000000' : n.toFixed(6);
const row = values => '[' + values.map(decimal).join(',') + ']';

function plates(buf) {
  if (buf.length < 16 || buf.toString('ascii', 0, 4) !== 'BDHC') throw Error('Invalid BDHC header');
  const counts = Array.from({length:6}, (_, i) => buf.readUInt16LE(4 + i * 2));
  const offsets = [], sizes = [8, 12, 4, 8, 8, 2];
  let end = 16;
  for (let i = 0; i < counts.length; i++) { offsets.push(end); end += counts[i] * sizes[i]; }
  if (end > buf.length) throw Error('Truncated BDHC sections');
  const point = index => {
    if (index >= counts[0]) throw Error('Invalid BDHC point index');
    const p = offsets[0] + index * 8;
    // The rectangular export uses whole tiles, flooring fractional endpoints.
    return [buf.readInt32LE(p) >> 16, buf.readInt32LE(p + 4) >> 16];
  };
  const out = [];
  for (let i = 0; i < counts[3]; i++) {
    const p = offsets[3] + i * 8, [x, y] = point(buf.readUInt16LE(p));
    const [right, bottom] = point(buf.readUInt16LE(p + 2)), w = right - x, h = bottom - y;
    const incline = buf.readUInt16LE(p + 4), distance = buf.readUInt16LE(p + 6);
    if (incline >= counts[1] || distance >= counts[2]) throw Error('Invalid BDHC plane index');
    const n = offsets[1] + incline * 12;
    const nx = buf.readInt32LE(n), ny = buf.readInt32LE(n + 4), nz = buf.readInt32LE(n + 8);
    const d = -buf.readInt32LE(offsets[2] + distance * 4) / 65536;
    let type = 6;
    if (nx === 0 && ny === 4096 && nz === 0) type = 0;
    else if (ny === 2896) {
      if (nx === 2896 && nz === 0) type = 2;
      else if (nx === -2896 && nz === 0) type = 3;
      else if (nx === 0 && nz === 2896) type = 4;
      else if (nx === 0 && nz === -2896) type = 5;
    }
    // Solve n.x*x + n.y*height + n.z*y + distance = 0. The
    // plate's z is its low edge, rounded to the export's millitile precision.
    let z = d;
    if (nx !== 0) z = d * Math.sqrt(1 + (nx / ny) ** 2) - nx / ny * (nx > 0 ? right : x);
    else if (nz !== 0) z = d * Math.sqrt(1 + (nz / ny) ** 2) - nz / ny * (nz > 0 ? bottom : y);
    z = f(Math.round(z * 1000) / 1000) || 0;
    let vertices;
    if (nz !== 0) {
      const rise = f(f(Math.abs(nz / ny)) * h), high = f(z + rise);
      vertices = nz < 0 ? [x,-y,z, right,-y,z, right,-bottom,high, x,-bottom,high]
        : [right,-y,high, x,-y,high, x,-bottom,z, right,-bottom,z];
    } else {
      const rise = nx === 0 ? 0 : f(f(Math.abs(nx / ny)) * w), high = f(z + rise);
      vertices = nx < 0 ? [x,-y,z, right,-y,high, right,-bottom,high, x,-bottom,z]
        : [right,-y,z, x,-y,high, x,-bottom,high, right,-bottom,z];
    }
    out.push('{"map":[0,0],"x":' + x + ',"y":' + y + ',"w":' + w + ',"h":' + h
      + ',"z":' + decimal(z) + ',"type":' + type + ',"v":' + row(vertices.map(n => n === 0 ? 0 : n)) + '}');
  }
  return '[' + out.join(',') + ']\r\n';
}


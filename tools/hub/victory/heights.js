function bw2Terrain(buf) {
  const cells = 32 * 32, tail = 4 + cells * 8;
  if (buf.length < tail || buf.readUInt16LE(0) !== 32 || buf.readUInt16LE(2) !== 32)
    throw Error('Invalid Black 2 permission size');
  const plane = (inclination, distance, x, y) => {
    const slope = slopes[inclination];
    if (!slope) throw Error('Unsupported Black 2 inclination ' + inclination);
    if (distance >= distances.length) throw Error('Invalid Black 2 distance index');
    const [sx, sy] = slope, d = distances[distance];
    const intercept = f(d * Math.sqrt(1 + f(sx * sx) + f(sy * sy)));
    return f(f(f(sx * (x - 16)) + f(sy * (y - 16))) + intercept);
  };
  const out = [];
  for (let y = 0; y < 32; y++) for (let x = 0; x < 32; x++) {
    const p = 4 + (y * 32 + x) * 8, inclination = buf.readUInt16LE(p), distance = buf.readUInt16LE(p + 2);
    let top = inclination, bottom = inclination, topDistance = distance, bottomDistance = distance;
    if (inclination === 2) {
      const c = tail + distance * 8;
      if (c + 8 > buf.length) throw Error('Invalid Black 2 corner index');
      top = buf.readUInt16LE(c) - 1; bottom = buf.readUInt16LE(c + 2) * 4;
      topDistance = buf.readUInt16LE(c + 4); bottomDistance = buf.readUInt16LE(c + 6);
    }
    out.push(row([plane(top, topDistance, x, y), plane(top, topDistance, x + 1, y),
      plane(bottom, bottomDistance, x + 1, y + 1), plane(bottom, bottomDistance, x, y + 1)]));
  }
  return '[' + out.join(',') + ']\r\n';
}

